local function run()
  local lazy = require('lazy.core.config')
  assert(lazy.plugins['nvim-pele-mermaid'], 'nvim-pele-mermaid is not registered')
  local source = vim.api.nvim_create_buf(true, false)
  vim.api.nvim_set_current_buf(source)
  local lines = { '# First diagram', '', '```mermaid', 'flowchart LR', 'A[Source] --> B[Reading view]', '```', '',
    '# Second diagram', '', '```mermaid', 'flowchart TD', 'C[Next] --> D[Done]', '```', '', 'Prose stays intact.' }
  vim.api.nvim_buf_set_lines(source, 0, -1, false, lines)
  vim.bo[source].filetype = 'markdown'
  assert(vim.fn.exists(':MermaidToggle') == 2, 'opening Markdown must register plugin commands')
  local plugin = require('pele_mermaid')
  local image = require('image')
  vim.api.nvim_win_set_cursor(0, { 5, 0 })
  local source_win = vim.api.nvim_get_current_win()
  vim.wait(200)
  assert(vim.api.nvim_get_current_buf() == source and vim.bo[source].modifiable, 'opening Markdown must stay editable source')
  assert(#image.get_images({buffer=source}) == 0, 'source must not auto-render inline images')
  local function await_image(predicate)
    local found
    assert(vim.wait(15000, function()
      for _, img in ipairs(image.get_images()) do
        if predicate(img) then found = img; return true end
      end
      return false
    end, 20), 'image was not created')
    assert(vim.fn.filereadable(found.original_path) == 1, 'PNG missing')
    return found
  end
  local function fingerprint(path)
    local file = assert(io.open(path, 'rb'))
    local bytes = file:read('*a')
    file:close()
    return vim.fn.sha256(bytes)
  end
  vim.cmd('MermaidToggle')
  local projection = vim.api.nvim_get_current_buf()
  assert(projection ~= source and not vim.bo[projection].modifiable, 'reading view must be separate and nonmodifiable')
  local read_image = await_image(function(img) return img.buffer == projection end)
  print('READ PNG: ' .. read_image.original_path)
  vim.cmd('MermaidNext')
  vim.cmd('MermaidSplit')
  local projected_split = await_image(function(img) return img.buffer ~= projection and img.buffer ~= source end)
  assert(projected_split.image_height > projected_split.image_width, 'split opened from second projection anchor must show its vertical diagram')
  vim.cmd('MermaidSplit')
  vim.cmd('MermaidPrev')
  vim.cmd('MermaidToggle')
  assert(vim.api.nvim_get_current_buf() == source, 'toggle must restore source')
  assert(vim.deep_equal(vim.api.nvim_buf_get_lines(source,0,-1,false),lines), 'reading/navigation changed source')
  vim.api.nvim_win_set_cursor(source_win, {5,0})
  vim.cmd('MermaidSplit')
  local split = await_image(function(img) return img.buffer ~= source and img.buffer ~= projection end)
  local old_hash = fingerprint(split.original_path)
  vim.api.nvim_buf_set_lines(source,4,5,false,{'A[Edited] --> B[Live update]'})
  vim.api.nvim_exec_autocmds('TextChanged',{buffer=source})
  local updated = await_image(function(img) return img.buffer == split.buffer and fingerprint(img.original_path) ~= old_hash end)
  print('LIVE PNG: ' .. updated.original_path)
  vim.cmd('MermaidSplit')
  vim.cmd('MermaidPreview')
  local floating = await_image(function(img) return img.buffer ~= source and img.buffer ~= projection and img.buffer ~= split.buffer end)
  print('FLOAT PNG: ' .. floating.original_path)
  vim.cmd('MermaidPreview')
  vim.api.nvim_set_current_win(source_win)
  vim.cmd('MermaidInspect')
  local inspector = vim.api.nvim_get_current_buf()
  await_image(function(img) return img.buffer == inspector end)
  vim.cmd('MermaidInspect')
  vim.api.nvim_set_current_win(source_win)
  local directory = vim.fn.tempname()
  vim.fn.mkdir(directory, 'p')
  vim.cmd('MermaidExport ' .. vim.fn.fnameescape(directory .. '/diagram.svg'))
  assert(vim.wait(15000,function() return vim.fn.filereadable(directory .. '/diagram.svg') == 1 end,20), 'SVG export missing')
  vim.cmd('MermaidExport ' .. vim.fn.fnameescape(directory .. '/diagram.png'))
  assert(vim.wait(15000,function() return vim.fn.filereadable(directory .. '/diagram.png') == 1 end,20), 'PNG export missing')
  print('EXPORTS: ' .. directory)
  plugin.stop()
  assert(vim.api.nvim_buf_get_lines(source,14,15,false)[1] == 'Prose stays intact.', 'preview operations changed prose')
  print('PASS: installed source-first reading/navigation, unchanged source, live split, float, inspector, SVG/PNG exports and cleanup')
end
local ok, err = xpcall(run,debug.traceback)
if not ok then io.stderr:write(err .. '\n'); vim.cmd('cquit 1') end
vim.cmd('qa!')
